"""Generate parameter definitions and bilingual text from reviewed source data."""
from pathlib import Path
import json
ROOT = Path(__file__).resolve().parents[1]
def generate():
    balance = json.loads((ROOT / 'balance.json').read_text())
    out = '# Generated by tools/build_content.py; edit balance.json.\n'
    out += ''.join(f'fia_{key} = {value}\n' for key, value in balance.items())
    (ROOT / 'mod/common/script_values/fia_parameters.txt').write_text(out, encoding='utf-8-sig')
    strings = json.loads((ROOT / 'localization.json').read_text())
    for language in ('english', 'simp_chinese'):
        text = f'l_{language}:\n'
        for key, value in strings.items():
            text += f' {key}:0 {json.dumps(value[language], ensure_ascii=False)}\n'
        (ROOT / f'mod/localization/{language}/fia_l_{language}.yml').write_text(text, encoding='utf-8-sig')
if __name__ == '__main__':
    generate()
